CREATE TABLE place_collection_temp (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id BIGINT NOT NULL,
    provider VARCHAR(30) NOT NULL,
    provider_place_id VARCHAR(100) NOT NULL,
    default_place_type VARCHAR(20) NOT NULL,
    name VARCHAR(200) NOT NULL,
    address_name VARCHAR(500),
    road_address_name VARCHAR(500),
    kakao_category_name VARCHAR(500),
    kakao_category_group_code VARCHAR(20),
    latitude NUMERIC(10, 7) NOT NULL,
    longitude NUMERIC(10, 7) NOT NULL,
    kakao_place_url VARCHAR(1000),
    phone VARCHAR(50),
    naver_title VARCHAR(200),
    naver_place_url VARCHAR(1000),
    naver_category_name VARCHAR(500),
    naver_address_name VARCHAR(500),
    naver_road_address_name VARCHAR(500),
    naver_matched_at TIMESTAMP,
    processing_step VARCHAR(30) NOT NULL DEFAULT 'NAVER_ENRICHMENT',
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempt_count INTEGER NOT NULL DEFAULT 0,
    error_code VARCHAR(100),
    error_message VARCHAR(1000),
    last_attempt_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_place_collection_temp_area FOREIGN KEY (area_id) REFERENCES areas (id),
    CONSTRAINT uk_place_collection_temp_provider_place UNIQUE (provider, provider_place_id),
    CONSTRAINT ck_place_collection_temp_provider CHECK (provider = 'KAKAO'),
    CONSTRAINT ck_place_collection_temp_place_type CHECK (default_place_type IN ('ACTIVITY', 'MEAL', 'CAFE')),
    CONSTRAINT ck_place_collection_temp_step CHECK (processing_step IN ('NAVER_ENRICHMENT', 'AI_TAGGING')),
    CONSTRAINT ck_place_collection_temp_status CHECK (status IN ('PENDING', 'PROCESSING', 'FAILED')),
    CONSTRAINT ck_place_collection_temp_attempt_count CHECK (attempt_count >= 0)
);

CREATE INDEX idx_place_collection_temp_step_status_id
    ON place_collection_temp (processing_step, status, id);
